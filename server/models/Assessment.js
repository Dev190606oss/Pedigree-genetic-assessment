const mongoose = require('mongoose');
const { RESULT_CATEGORIES } = require('../constants');

const assessmentSchema = new mongoose.Schema(
  {
    familyId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Family',
      required: true,
      index: true
    },
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true
    },
    inputSnapshot: {
      family: { type: mongoose.Schema.Types.Mixed },
      members: [{ type: mongoose.Schema.Types.Mixed }],
      relationships: [{ type: mongoose.Schema.Types.Mixed }],
      conditions: [{ type: mongoose.Schema.Types.Mixed }]
    },
    facts: {
      type: Map,
      of: mongoose.Schema.Types.Mixed,
      default: {}
    },
    triggeredRules: [
      {
        ruleId: { type: mongoose.Schema.Types.ObjectId, ref: 'Rule' },
        ruleCode: String,
        name: String,
        version: Number,
        priority: Number,
        category: String,
        resultCategory: String,
        matchingFacts: mongoose.Schema.Types.Mixed,
        explanation: String,
        guidance: [String]
      }
    ],
    resultCategory: {
      type: String,
      enum: Object.values(RESULT_CATEGORIES),
      required: true
    },
    summary: {
      type: String,
      required: true
    },
    guidance: {
      type: [String],
      default: []
    },
    disclaimer: {
      type: String,
      default: 'This preconception genetic assessment is generated by an academic decision-support expert system for educational purposes only. It does NOT constitute medical diagnosis, clinical prognosis, or clinical genetic advice. Consult a certified medical geneticist or healthcare professional for individualized clinical evaluation.'
    },
    engineVersion: {
      type: String,
      default: '1.0.0'
    }
  },
  {
    timestamps: true
  }
);

module.exports = mongoose.model('Assessment', assessmentSchema);
