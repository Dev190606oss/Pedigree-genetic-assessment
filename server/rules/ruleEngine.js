const { evaluateCondition } = require('./ruleOperators');
const { RESULT_CATEGORIES } = require('../constants');

const ENGINE_VERSION = '1.0.0';

const CATEGORY_WEIGHTS = {
  [RESULT_CATEGORIES.COUNSELOR_REVIEW]: 4,
  [RESULT_CATEGORIES.REVIEW_RECOMMENDED]: 3,
  [RESULT_CATEGORIES.INSUFFICIENT_INFORMATION]: 2,
  [RESULT_CATEGORIES.INFORMATIONAL]: 1
};

/**
 * Deterministic AIES Rule Evaluation Engine
 * @param {Object} facts - Normalized facts extracted by factBuilder
 * @param {Array} rules - Active rules to evaluate against
 * @returns {Object} assessment output containing resultCategory, triggeredRules, explanation, guidance
 */
function evaluateRules(facts, rules = []) {
  const activeRules = rules
    .filter(r => r.isActive !== false)
    .sort((a, b) => (b.priority || 0) - (a.priority || 0));

  const triggeredRules = [];
  let highestWeight = 0;
  let dominantCategory = RESULT_CATEGORIES.INFORMATIONAL;

  for (const rule of activeRules) {
    let allConditionsMet = true;
    const matchingFacts = {};

    for (const cond of (rule.conditions || [])) {
      const factValue = facts[cond.fact];
      const isMet = evaluateCondition(factValue, cond.operator, cond.value);

      matchingFacts[cond.fact] = {
        actualValue: factValue,
        operator: cond.operator,
        expectedValue: cond.value,
        satisfied: isMet
      };

      if (!isMet) {
        allConditionsMet = false;
        break;
      }
    }

    if (allConditionsMet && rule.conditions && rule.conditions.length > 0) {
      triggeredRules.push({
        ruleId: rule._id,
        ruleCode: rule.ruleCode || rule._id?.toString() || 'RULE-CUSTOM',
        name: rule.name,
        version: rule.version || 1,
        priority: rule.priority || 10,
        category: rule.category || 'GENERAL',
        resultCategory: rule.result?.category || RESULT_CATEGORIES.REVIEW_RECOMMENDED,
        matchingFacts,
        explanation: rule.explanation,
        guidance: rule.guidance || []
      });

      // Update dominant result category based on severity priority
      const ruleCategory = rule.result?.category || RESULT_CATEGORIES.INFORMATIONAL;
      const weight = CATEGORY_WEIGHTS[ruleCategory] || 1;
      if (weight > highestWeight) {
        highestWeight = weight;
        dominantCategory = ruleCategory;
      }
    }
  }

  // Fallback if no rules triggered
  if (triggeredRules.length === 0) {
    dominantCategory = facts.required_family_information_missing
      ? RESULT_CATEGORIES.INSUFFICIENT_INFORMATION
      : RESULT_CATEGORIES.INFORMATIONAL;
  }

  // Synthesize human-readable explainable summary
  let summary = '';
  if (triggeredRules.length === 0) {
    summary = 'No specific hereditary risks or conditions met standard assessment thresholds in the provided family data.';
  } else {
    const topRule = triggeredRules[0];
    summary = `Assessment triggered ${triggeredRules.length} rule${triggeredRules.length > 1 ? 's' : ''}. Primary observation: ${topRule.name}. Categorized as ${dominantCategory.replace(/_/g, ' ')}.`;
  }

  // Collect distinct guidance points
  const guidanceSet = new Set();
  triggeredRules.forEach(r => {
    (r.guidance || []).forEach(g => guidanceSet.add(g));
  });

  if (guidanceSet.size === 0) {
    guidanceSet.add('Consult a certified genetic counselor or healthcare professional for individualized preconception advice.');
    guidanceSet.add('Keep family medical history updated as new clinical information becomes available.');
  }

  return {
    engineVersion: ENGINE_VERSION,
    resultCategory: dominantCategory,
    summary,
    facts,
    triggeredRules,
    guidance: Array.from(guidanceSet),
    disclaimer: 'This preconception genetic assessment is generated by an academic decision-support expert system for educational purposes only. It does NOT constitute medical diagnosis, clinical prognosis, or clinical genetic advice. Consult a certified medical geneticist or healthcare professional for individualized clinical evaluation.'
  };
}

module.exports = {
  evaluateRules,
  ENGINE_VERSION
};
